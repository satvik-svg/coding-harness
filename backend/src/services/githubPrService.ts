import os from 'os';
import path from 'path';
import fs from 'fs/promises';
import { execFile } from 'child_process';
import { promisify } from 'util';
import { CreatePullRequestResult } from '@coding-harness/shared';
import { logger } from '../logger';

const execFileAsync = promisify(execFile);

export interface OpenPrOptions {
  taskId: string;
  repoUrl: string;
  diff: string;
  prompt: string;
  githubToken: string;
  branchName?: string;
  baseBranch?: string;
  title?: string;
  body?: string;
}

function parseGitHubRepo(repoUrl: string): { owner: string; repo: string } {
  let url: URL;
  try {
    url = new URL(repoUrl.trim());
  } catch {
    throw new Error('Only valid HTTPS GitHub repository URLs support opening a Pull Request.');
  }

  if (url.protocol !== 'https:' || url.hostname !== 'github.com') {
    throw new Error('Opening a Pull Request is currently supported for https://github.com repositories.');
  }

  const parts = url.pathname
    .replace(/\.git$/i, '')
    .split('/')
    .filter(Boolean);

  if (parts.length !== 2) {
    throw new Error('Could not parse GitHub owner and repository name from URL.');
  }

  return { owner: parts[0], repo: parts[1] };
}

function sanitizeBranchName(raw: string): string {
  const cleaned = raw
    .trim()
    .replace(/[^A-Za-z0-9/_.-]/g, '-')
    .replace(/\.{2,}/g, '-')
    .replace(/^\/+|\/+$/g, '');
  if (!cleaned) {
    throw new Error('Branch name is invalid.');
  }
  return cleaned;
}

function redactToken(text: string, token: string): string {
  if (!token) return text;
  return text.split(token).join('[REDACTED]').split(encodeURIComponent(token)).join('[REDACTED]');
}

export class GitHubPrService {
  static async openPullRequestFromDiff(options: OpenPrOptions): Promise<CreatePullRequestResult> {
    const { taskId, repoUrl, diff, prompt, githubToken } = options;
    const token = githubToken.trim();
    if (!token) {
      throw new Error('A GitHub Personal Access Token is required.');
    }
    if (!diff || !diff.trim()) {
      throw new Error('This task has no generated Git diff to open a Pull Request with.');
    }

    const { owner, repo } = parseGitHubRepo(repoUrl);
    const ghHeaders = {
      Authorization: `Bearer ${token}`,
      Accept: 'application/vnd.github+json',
      'X-GitHub-Api-Version': '2022-11-28',
      'Content-Type': 'application/json',
      'User-Agent': 'coding-harness',
    };

    // 1. Resolve repository default branch from GitHub API
    let baseBranch = options.baseBranch?.trim() || '';
    if (!baseBranch) {
      const repoRes = await fetch(`https://api.github.com/repos/${owner}/${repo}`, {
        headers: ghHeaders,
      });
      if (!repoRes.ok) {
        const errBody = await repoRes.json().catch(() => ({}));
        throw new Error(
          `GitHub API error (${repoRes.status}): ${(errBody as { message?: string }).message || 'Unable to inspect repository. Verify your token has repo access.'}`,
        );
      }
      const repoJson = (await repoRes.json()) as { default_branch?: string };
      baseBranch = repoJson.default_branch || 'main';
    }

    const branchName = sanitizeBranchName(
      options.branchName || `coding-harness/${taskId.substring(0, 8)}-${Date.now().toString(36)}`,
    );
    const prTitle =
      options.title?.trim() ||
      `Coding Harness: ${prompt.trim().replace(/\s+/g, ' ').slice(0, 72)}`;
    const prBody =
      options.body?.trim() ||
      `Automated change generated by **Coding Harness**.\n\n### Prompt\n> ${prompt.trim()}\n\n*Task ID: \`${taskId}\`*`;

    const tmpRoot = await fs.mkdtemp(path.join(os.tmpdir(), `ch-pr-${taskId.substring(0, 8)}-`));
    const repoDir = path.join(tmpRoot, 'repo');
    const patchFile = path.join(tmpRoot, 'changes.patch');

    try {
      await fs.writeFile(patchFile, diff.endsWith('\n') ? diff : `${diff}\n`, 'utf8');

      const authHeader = `AUTHORIZATION: basic ${Buffer.from(`x-access-token:${token}`).toString('base64')}`;
      const runGit = async (args: string[], cwd?: string) => {
        try {
          return await execFileAsync(
            'git',
            [
              '-c',
              'credential.helper=',
              '-c',
              `http.https://github.com/.extraheader=${authHeader}`,
              ...args,
            ],
            {
              cwd,
              env: { ...process.env, GIT_TERMINAL_PROMPT: '0' },
              maxBuffer: 10 * 1024 * 1024,
            },
          );
        } catch (err: unknown) {
          const e = err as Error & { stderr?: string };
          const msg = redactToken(e.stderr || e.message || 'Git operation failed', token);
          throw new Error(msg);
        }
      };

      logger.info(`Opening PR for ${owner}/${repo} on branch ${branchName} (base: ${baseBranch})`);

      // 2. Shallow clone base branch
      await runGit([
        'clone',
        '--depth',
        '1',
        '--branch',
        baseBranch,
        `https://github.com/${owner}/${repo}.git`,
        repoDir,
      ]);

      // 3. Configure committer & create feature branch
      await runGit(['config', 'user.name', 'Coding Harness'], repoDir);
      await runGit(['config', 'user.email', 'agent@coding-harness.local'], repoDir);
      await runGit(['checkout', '-b', branchName], repoDir);

      // 4. Apply generated patch & commit
      await runGit(['apply', '--whitespace=nowarn', patchFile], repoDir);
      await runGit(['add', '-A'], repoDir);
      await runGit(['commit', '-m', prTitle], repoDir);

      // 5. Push new branch to origin
      try {
        await runGit(['push', '-u', 'origin', branchName], repoDir);
      } catch (pushErr) {
        const pushMsg = (pushErr as Error).message || '';
        if (pushMsg.includes('[rejected]') || pushMsg.includes('non-fast-forward')) {
          throw new Error(
            `Branch "${branchName}" already exists on GitHub. Choose a new branch name or check your open Pull Requests.`,
          );
        }
        throw pushErr;
      }

      // 6. Create Pull Request via GitHub REST API
      const prRes = await fetch(`https://api.github.com/repos/${owner}/${repo}/pulls`, {
        method: 'POST',
        headers: ghHeaders,
        body: JSON.stringify({
          title: prTitle,
          head: branchName,
          base: baseBranch,
          body: prBody,
        }),
      });

      const prJson = (await prRes.json().catch(() => ({}))) as {
        html_url?: string;
        number?: number;
        title?: string;
        message?: string;
        errors?: Array<{ message?: string }>;
      };

      if (!prRes.ok || !prJson.html_url || !prJson.number) {
        const detail =
          prJson.errors?.map((e) => e.message).filter(Boolean).join('; ') ||
          prJson.message ||
          `GitHub PR creation failed (${prRes.status})`;
        throw new Error(detail);
      }

      return {
        prUrl: prJson.html_url,
        prNumber: prJson.number,
        branchName,
        baseBranch,
        title: prJson.title || prTitle,
      };
    } finally {
      await fs.rm(tmpRoot, { recursive: true, force: true }).catch(() => {});
    }
  }
}
